def _page_items(segments: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], dict[str, set[str]]]:
    """Build a stable ID-addressed page payload for both batch requests."""
    items: list[dict[str, Any]] = []
    expected: dict[str, set[str]] = {}
    seen_segments: set[str] = set()
    for index, segment in enumerate(segments):
        segment_id = str(segment.get("id", "")).strip()
        if not segment_id or segment_id in seen_segments:
            raise ValueError(f"invalid or duplicate segment id at index {index}")
        seen_segments.add(segment_id)
        sentence = target_sentence(segment)
        words: list[dict[str, str]] = []
        word_ids: set[str] = set()
        raw_words = segment.get("words", [])
        if not isinstance(raw_words, list):
            raise ValueError(f"segment {segment_id} words must be an array")
        for word_index, word in enumerate(raw_words):
            if not isinstance(word, dict):
                raise ValueError(f"segment {segment_id} word {word_index} is invalid")
            source = normalize_source_text(word.get("text", ""))
            # Older drafts may still contain punctuation-only OCR boxes.
            # Keep punctuation in target_sentence, but never send these as
            # independent word/meaning requests to the translation model.
            if not source or not any(character.isalnum() for character in source):
                continue
            word_id = str(word.get("id", "")).strip()
            if not word_id or word_id in word_ids:
                raise ValueError(f"invalid or duplicate word id in segment {segment_id}")
            word_ids.add(word_id)
            words.append(
                {
                    "id": word_id,
                    "text": source,
                    # Sending an existing value gives the reviewer context,
                    # but the apply step below never overwrites it.
                    "phonetic": str(word.get("phonetic", "") or "").strip(),
                }
            )
        expected[segment_id] = word_ids
        items.append(
            {
                "id": segment_id,
                "context": page_context(segments, index),
                "target_text": sentence,
                "words": words,
            }
        )
    return items, expected


