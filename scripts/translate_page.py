MAX_TRANSLATION_COMPLETION_TOKENS = 131072


def configured_translation_completion_tokens() -> int:
    raw = os.getenv(
        "TRANSLATION_MAX_COMPLETION_TOKENS",
        str(MAX_TRANSLATION_COMPLETION_TOKENS),
    ).strip()
    try:
        value = int(raw)
    except ValueError as exc:
        raise RuntimeError("TRANSLATION_MAX_COMPLETION_TOKENS must be an integer") from exc
    if value < 1 or value > MAX_TRANSLATION_COMPLETION_TOKENS:
        raise RuntimeError(
            "TRANSLATION_MAX_COMPLETION_TOKENS must be between 1 and "
            f"{MAX_TRANSLATION_COMPLETION_TOKENS} for qwen3.7-flash"
        )
    return value


