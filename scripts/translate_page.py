def parse_batch_translation(value: Any, expected: dict[str, set[str]]) -> dict[str, dict[str, Any]]:
    payload = json.loads(_clean_json_payload(value))
    if not isinstance(payload, dict) or not isinstance(payload.get("segments"), list):
        raise ValueError("batch translator response must contain a segments array")
    result: dict[str, dict[str, Any]] = {}
    for raw in payload["segments"]:
        if not isinstance(raw, dict):
            raise ValueError("batch translator segment must be an object")
        segment_id = str(raw.get("id", "")).strip()
        if segment_id in result or segment_id not in expected:
            raise ValueError(f"batch translator returned unexpected segment id: {segment_id}")
        translation = clean_translation(raw.get("translation", ""))
        if not translation:
            raise ValueError(f"batch translator returned empty translation: {segment_id}")
        raw_words = raw.get("words", [])
        if not isinstance(raw_words, list):
            raise ValueError(f"batch translator words must be an array: {segment_id}")
        words: dict[str, dict[str, str]] = {}
        for word in raw_words:
            if not isinstance(word, dict):
                raise ValueError(f"batch translator word must be an object: {segment_id}")
            word_id = str(word.get("id", "")).strip()
            if word_id in words or word_id not in expected[segment_id]:
                raise ValueError(f"batch translator returned unexpected word id: {word_id}")
            meaning = clean_translation(word.get("meaning", ""))
            if not meaning:
                raise ValueError(f"batch translator returned empty meaning: {word_id}")
            if "phonetic" not in word or not isinstance(word.get("phonetic"), str):
                raise ValueError(f"batch translator returned invalid phonetic: {word_id}")
            words[word_id] = {
                "meaning": meaning,
                "phonetic": clean_phonetic(word.get("phonetic", "")),
            }
        if set(words) != expected[segment_id]:
            raise ValueError(f"batch translator word IDs do not match segment {segment_id}")
        result[segment_id] = {"translation": translation, "words": words}
    if set(result) != set(expected):
        raise ValueError("batch translator segment IDs do not match the input page")
    return result


def parse_batch_review(
    value: Any,
    candidates: dict[str, dict[str, Any]],
    expected: dict[str, set[str]],
) -> dict[str, dict[str, Any]]:
    payload = json.loads(_clean_json_payload(value))
    if not isinstance(payload, dict) or set(payload) != {"issues"}:
        raise ValueError("batch reviewer response must contain only an issues array")
    if not isinstance(payload["issues"], list):
        raise ValueError("batch reviewer issues must be an array")

    # Start from the translator's validated page and overlay only the fields
    # the reviewer explicitly identifies as incorrect.
    result: dict[str, dict[str, Any]] = {
        segment_id: {
            "translation": candidate["translation"],
            "issues": [],
            "passed": True,
            "words": {
                word_id: {
                    "meaning": word["meaning"],
                    "phonetic": word["phonetic"],
                    "issues": [],
                }
                for word_id, word in candidate["words"].items()
            },
        }
        for segment_id, candidate in candidates.items()
    }

    seen: set[tuple[str, str, str]] = set()
    for raw in payload["issues"]:
        required = {"segment_id", "word_id", "field", "reason", "suggestion"}
        if not isinstance(raw, dict) or set(raw) != required:
            raise ValueError("batch reviewer issue has an invalid shape")
        segment_id = str(raw["segment_id"]).strip()
        word_id = str(raw["word_id"]).strip()
        field = str(raw["field"]).strip()
        reason = str(raw["reason"]).strip()
        suggestion = str(raw["suggestion"]).strip()
        if segment_id not in expected:
            raise ValueError(f"batch reviewer returned unexpected segment id: {segment_id}")
        if field not in {"translation", "meaning", "phonetic"} or not reason:
            raise ValueError("batch reviewer issue has an invalid field or reason")
        if field == "translation":
            if word_id:
                raise ValueError("sentence translation issue must not include a word ID")
            correction = clean_translation(suggestion)
            if not correction:
                raise ValueError("sentence translation correction must not be empty")
            result[segment_id]["translation"] = correction
            result[segment_id]["issues"].append(reason)
            result[segment_id]["passed"] = False
        else:
            if word_id not in expected[segment_id]:
                raise ValueError(f"batch reviewer returned unexpected word id: {word_id}")
            word_result = result[segment_id]["words"][word_id]
            if field == "meaning":
                correction = clean_translation(suggestion)
                if not correction:
                    raise ValueError(f"word meaning correction must not be empty: {word_id}")
                word_result["meaning"] = correction
            else:
                correction = clean_phonetic(suggestion)
                word_result["phonetic"] = correction
            word_result["issues"].append(reason)
            result[segment_id]["passed"] = False
        issue_key = (segment_id, word_id, field)
        if issue_key in seen:
            raise ValueError("batch reviewer returned a duplicate issue")
        seen.add(issue_key)
    return result


def _set_request_context(
    backend: GenerationBackend, kind: str, page: int | str | None, attempt: int
) -> None:
    setter = getattr(backend, "set_request_context", None)
    if callable(setter):
        setter(kind, page, attempt)


def _generate_once(
    backend: GenerationBackend,
    system_prompt: str,
    prompt: str,
    max_completion_tokens: int,
    *,
    schema_name: str | None,
    schema: dict[str, Any] | None,
) -> str:
    structured = getattr(backend, "generate_structured", None)
    if schema is not None and callable(structured):
        return structured(
            system_prompt,
            prompt,
            max_completion_tokens,
            schema_name=schema_name or "translation_result",
            schema=schema,
        )
    return backend.generate(system_prompt, prompt, max_completion_tokens)


def _call_once(
    backend: GenerationBackend,
    system_prompt: str,
    prompt: str,
    *,
    kind: str,
    page: int | str | None,
    parser: Any,
    max_completion_tokens: int,
    schema_name: str | None = None,
    schema: dict[str, Any] | None = None,
) -> Any:
    token_budget = max_completion_tokens
    set_operation = getattr(backend, "set_operation", None)
    set_status_callback = getattr(backend, "set_status_callback", None)
    if callable(set_operation):
        label = {"page_translation": "整页翻译", "page_review": "整页审核"}.get(
            kind, kind.replace("_", " ")
        )
        try:
            set_operation(label, request_type=kind)
        except TypeError:
            set_operation(label)
    if callable(set_status_callback):
        set_status_callback(
            lambda message: print(
                json.dumps({"event": "status", "message": message}, ensure_ascii=False),
                flush=True,
            )
        )
    report_status = getattr(backend, "_report_status", None)
    raw: str | None = None
    try:
        _set_request_context(backend, kind, page, 1)
        if callable(report_status):
            report_status(f"正在请求{getattr(backend, 'operation_label', kind)}模型")
        raw = _generate_once(
            backend,
            system_prompt,
            prompt,
            token_budget,
            schema_name=schema_name,
            schema=schema,
        )
        return parser(raw)
    except Exception as exc:
        log_failure(
            kind=kind,
            target="page",
            context="",
            error=exc,
            attempt=1,
            page=page,
            model=getattr(backend, "model", ""),
            raw=raw,
        )
        recorder = getattr(backend, "record_failure", None)
        if callable(recorder):
            recorder(kind)
        raise
    finally:
        if callable(set_status_callback):
            set_status_callback(None)


def log_translation(
    *, kind: str, target: str, context: str, result: TranslationResult, word: str = ""
) -> None:
    payload: dict[str, Any] = {
        "request_type": f"{kind}_translation",
        "source_length": len(target),
        "context_length": len(context),
        "translation_length": len(result.translation),
        "review": result.review,
    }
    if result.score is not None:
        payload["score"] = round(result.score, 4)
    if result.issues:
        payload["issues"] = result.issues
    if os.getenv("TRANSLATION_DEBUG", "").strip().lower() in {"1", "true", "yes"}:
        payload["source_preview"] = target[:120]
        payload["translation_preview"] = result.translation[:120]
    prefix = "[TRANSLATION WARNING]" if result.review != "PASS" else "[TRANSLATION]"
    print(prefix, json.dumps(payload, ensure_ascii=False), file=sys.stderr, flush=True)


def log_failure(
    *,
    kind: str,
    target: str,
    context: str,
    error: Exception,
    attempt: int,
    page: int | str | None = None,
    model: str = "",
    raw: str | None = None,
) -> None:
    payload: dict[str, Any] = {
        "request_type": kind,
        "page": page,
        "model": model,
        "attempt": attempt,
        "error_type": type(error).__name__,
        "error": str(error)[:800],
        "source_length": len(target),
        "context_length": len(context),
    }
    if raw is not None:
        payload["response_length"] = len(raw)
    if isinstance(error, json.JSONDecodeError):
        payload.update({"line": error.lineno, "column": error.colno, "position": error.pos})
    if raw is not None and os.getenv("TRANSLATION_DEBUG", "").strip().lower() in {"1", "true", "yes"}:
        payload["response_preview"] = raw[:1200]
    print(
        "[TRANSLATION WARNING]",
        json.dumps(payload, ensure_ascii=False),
        file=sys.stderr,
        flush=True,
    )


def _batch_generate(
    backend: GenerationBackend,
    system_prompt: str,
    prompt: str,
    *,
    kind: str,
    stage_label: str,
    parser: Any,
    schema: dict[str, Any] | None = None,
    page: int | str | None = None,
    max_completion_tokens: int = 1024,
) -> Any:
    # Kept as a thin named wrapper because translation/review call sites need
    # explicit request types and separate schemas in their logs.
    del stage_label
    return _call_once(
        backend,
        system_prompt,
        prompt,
        kind=kind,
        page=page,
        parser=parser,
        max_completion_tokens=max_completion_tokens,
        schema_name=kind,
        schema=schema,
    )


def generate_candidate(
    backend: GenerationBackend,
    system_prompt: str,
    prompt: str,
    *,
    kind: str,
    target: str,
    context: str,
) -> str:
    del target, context

    def parse(raw: str) -> str:
        candidate = clean_translation(raw)
        if not candidate:
            raise ValueError("translation produced empty output")
        return candidate

    return _call_once(
        backend,
        system_prompt,
        prompt,
        kind=f"{kind}_translation",
        page=None,
        parser=parse,
        max_completion_tokens=256,
    )


def review_candidate(
    backend: GenerationBackend,
    *,
    kind: str,
    target: str,
    context: str,
    candidate: str,
) -> ReviewResult:
    prompt = reviewer_prompt(kind, context, target, candidate)
    review_error: Exception | None = None
    try:
        return _call_once(
            backend,
            REVIEWER_SYSTEM_PROMPT,
            prompt,
            kind=f"{kind}_review",
            page=None,
            parser=lambda raw: parse_review(raw, candidate),
            max_completion_tokens=384,
            schema_name="single_translation_review",
            schema=SINGLE_REVIEW_SCHEMA,
        )
    except Exception as exc:
        review_error = exc
        print(
            "[TRANSLATION REVIEW WARNING]",
            json.dumps(
                {
                    "request_type": f"{kind}_review",
                    "model": getattr(backend, "model", ""),
                    "error_type": type(exc).__name__,
                    "error": str(exc)[:800],
                    "source_length": len(target),
                    "context_length": len(context),
                },
                ensure_ascii=False,
            ),
            file=sys.stderr,
            flush=True,
        )
    return ReviewResult(
        passed=False,
        score=0.0,
        issues=[f"reviewer_failed: {review_error or 'unknown error'}"],
        corrected_translation=candidate,
        reviewer_failed=True,
    )


def deterministic_issues(source: str, translation: str) -> list[str]:
    issues: list[str] = []
    if not translation:
        issues.append("empty translation")
    if NUMBER_RE.findall(source) != NUMBER_RE.findall(translation):
        issues.append("numbers/dates/times changed")
    if PREFIX_RE.match(translation):
        issues.append("unexpected translation label")
    return issues


def translate_target(
    backend: GenerationBackend,
    *,
    kind: str,
    target: str,
    context: str,
    sentence: str = "",
) -> TranslationResult:
    system = TRANSLATOR_SYSTEM_PROMPT if kind == "sentence" else WORD_TRANSLATOR_SYSTEM_PROMPT
    prompt = sentence_prompt(context, target) if kind == "sentence" else word_prompt(context, sentence, target)
    candidate = generate_candidate(
        backend,
        system,
        prompt,
        kind=kind,
        target=target,
        context=context,
    )
    review = review_candidate(
        backend,
        kind=kind,
        target=target,
        context=context,
        candidate=candidate,
    )
    final = clean_translation(review.corrected_translation) or candidate
    issues = list(review.issues)
    issues.extend(item for item in deterministic_issues(target, final) if item not in issues)
    passed = review.passed and review.score >= 0.85 and not issues and not review.reviewer_failed
    return TranslationResult(
        translation=final,
        score=review.score,
        issues=issues,
        review="PASS" if passed else ("REVIEWER_FAILED" if review.reviewer_failed else "WARNING"),
    )


def translate_page(content: dict[str, Any], backend: GenerationBackend) -> dict[str, Any]:
    raw_segments = content.get("segments", [])
    if not isinstance(raw_segments, list):
        raise ValueError("page JSON field segments must be an array")
    segments = [segment for segment in raw_segments if isinstance(segment, dict)]
    if not segments:
        print(json.dumps({"event": "progress", "stage": "done", "progress": 2, "total": 2}), flush=True)
        print(json.dumps({"translated": 0, "failed": 0}, ensure_ascii=False), flush=True)
        return content

    items, expected = _page_items(segments)
    page_number = content.get("page", content.get("page_no"))
    page_number = page_number if isinstance(page_number, (int, str)) else None
    word_count = sum(len(item["words"]) for item in items)
    segment_count = len(items)
    translation_token_budget = configured_translation_completion_tokens()
    review_token_budget = min(
        2048,
        max(384, 128 + word_count * 16 + segment_count * 24),
    )

    print(json.dumps({"event": "progress", "stage": "translator", "progress": 0, "total": 2}), flush=True)
    candidates = _batch_generate(
        backend,
        BATCH_TRANSLATOR_SYSTEM_PROMPT,
        batch_translation_prompt(items),
        kind="page_translation",
        stage_label="整页翻译",
        parser=lambda raw: parse_batch_translation(raw, expected),
        schema=BATCH_TRANSLATION_SCHEMA,
        page=page_number,
        max_completion_tokens=translation_token_budget,
    )
    print(json.dumps({"event": "progress", "stage": "reviewer", "progress": 1, "total": 2}), flush=True)
    review_items = []
    for item in items:
        candidate = candidates[item["id"]]
        review_items.append(
            {
                "id": item["id"],
                "context": item["context"],
                "target_text": item["target_text"],
                "candidate_translation": candidate["translation"],
                "words": [
                    {
                        "id": word["id"],
                        "text": word["text"],
                        "candidate_meaning": candidate["words"][word["id"]]["meaning"],
                        "candidate_phonetic": candidate["words"][word["id"]]["phonetic"],
                    }
                    for word in item["words"]
                ],
            }
        )
    review_failed = False
    try:
        reviewed = _batch_generate(
            backend,
            BATCH_REVIEWER_SYSTEM_PROMPT,
            batch_review_prompt(review_items),
            kind="page_review",
            stage_label="整页审核",
            parser=lambda raw: parse_batch_review(raw, candidates, expected),
            schema=BATCH_REVIEW_SCHEMA,
            page=page_number,
            max_completion_tokens=review_token_budget,
        )
    except Exception as exc:
        # Review only improves quality; a completed translation remains usable
        # if every review attempt fails. Keep translator candidates untouched.
        review_failed = True
        reviewed = {
            segment_id: {
                "translation": candidate["translation"],
                "issues": [],
                "passed": True,
                "score": None,
                "words": {
                    word_id: {
                        "meaning": word["meaning"],
                        "phonetic": word["phonetic"],
                        "issues": [],
                        "score": None,
                    }
                    for word_id, word in candidate["words"].items()
                },
            }
            for segment_id, candidate in candidates.items()
        }
        print(
            "[TRANSLATION REVIEW WARNING]",
            json.dumps(
                {
                    "request_type": "page_review",
                    "page": page_number,
                    "model": getattr(backend, "model", ""),
                    "error_type": type(exc).__name__,
                    "error": str(exc)[:800],
                    "fallback": "kept_page_translation",
                },
                ensure_ascii=False,
            ),
            file=sys.stderr,
            flush=True,
        )
    print(json.dumps({"event": "progress", "stage": "done", "progress": 2, "total": 2}), flush=True)

    # Coordinates, OCR confidence, IDs, images, and audio metadata are never
    # touched. Existing phonetics are never overwritten; only blanks may be
    # filled from the model's reviewed IPA value.
    translated = 0
    failed = 0
    phonetic_filled = 0
    phonetic_missing = 0
    for segment in segments:
        segment_id = str(segment["id"])
        result = reviewed[segment_id]
        segment["translation"] = result["translation"]
        segment_issues = list(result["issues"])
        segment_issues.extend(
            item
            for item in deterministic_issues(target_sentence(segment), result["translation"])
            if item not in segment_issues
        )
        if review_failed:
            review_status = "REVIEW_WARNING"
            if segment_issues:
                failed += 1
        elif result["passed"] and not segment_issues:
            review_status = "PASS"
        else:
            review_status = "WARNING"
            failed += 1
        translated += 1
        log_translation(
            kind="sentence",
            target=target_sentence(segment),
            context=next(item["context"] for item in items if item["id"] == segment_id),
            result=TranslationResult(result["translation"], result.get("score"), segment_issues, review_status),
        )
        words_by_id = {str(word.get("id", "")): word for word in segment.get("words", []) if isinstance(word, dict)}
        for word_id, word_result in result["words"].items():
            word = words_by_id[word_id]
            source = normalize_source_text(word.get("text", ""))
            word["meaning"] = word_result["meaning"]
            if not str(word.get("phonetic", "") or "").strip():
                phonetic = clean_phonetic(word_result.get("phonetic", ""))
                # A model occasionally echoes the English token instead of IPA.
                if phonetic and phonetic.casefold() != source.casefold():
                    word["phonetic"] = phonetic
                    phonetic_filled += 1
                else:
                    phonetic_missing += 1
            translated += 1
            if word_result["issues"]:
                failed += 1
            log_translation(
                kind="word",
                target=source,
                context=target_sentence(segment),
                result=TranslationResult(
                    word_result["meaning"],
                    word_result.get("score"),
                    word_result["issues"],
                    "REVIEW_WARNING" if review_failed else "PASS" if not word_result["issues"] else "WARNING",
                ),
            )

    print(
        json.dumps(
            {
                "translated": translated,
                "failed": failed,
                "phonetic_filled": phonetic_filled,
                "phonetic_missing": phonetic_missing,
                "review_warning": review_failed,
            },
            ensure_ascii=False,
        ),
        flush=True,
    )
    return content


def _required_env(name: str) -> str:
    value = os.getenv(name, "").strip()
    if not value:
        raise RuntimeError(f"{name} is not set")
    return value


def configured_backend(model_id: str = "") -> GenerationBackend:
    selected = (model_id or os.getenv("TRANSLATION_MODEL", "")).strip()
    if selected == "local-qwen3-4b-instruct-2507":
        return LocalMLXBackend()
    if not selected:
        selected = _required_env("TRANSLATION_MODEL")
    try:
        connect_timeout = float(os.getenv("TRANSLATION_CONNECT_TIMEOUT", "10"))
        read_timeout = float(os.getenv("TRANSLATION_READ_TIMEOUT", "90"))
    except ValueError as exc:
        raise RuntimeError("Invalid translation API timeout configuration") from exc
    if connect_timeout <= 0 or read_timeout <= 0:
        raise RuntimeError("Translation API timeouts must be positive")
    api_key = os.getenv("TRANSLATION_API_KEY", "").strip() or os.getenv("DASHSCOPE_API_KEY", "").strip()
    if not api_key:
        raise RuntimeError("TRANSLATION_API_KEY or DASHSCOPE_API_KEY is not set")
    base_url = os.getenv("TRANSLATION_API_BASE_URL", "").strip() or os.getenv("DASHSCOPE_BASE_URL", "").strip()
    if not base_url:
        raise RuntimeError("TRANSLATION_API_BASE_URL or DASHSCOPE_BASE_URL is not set")
    return OnlineLLMClient(
        base_url=base_url,
        api_key=api_key,
        model=selected,
        temperature=0.1,
        connect_timeout=connect_timeout,
        read_timeout=read_timeout,
    )


