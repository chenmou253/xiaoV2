class OnlineLLMClient:
    """One OpenAI-compatible client shared by translator and reviewer calls."""

    def __init__(
        self,
        *,
        base_url: str,
        api_key: str,
        model: str,
        temperature: float = 0.1,
        connect_timeout: float = 10.0,
        read_timeout: float = 90.0,
    ) -> None:
        try:
            import httpx
            from openai import OpenAI
        except ImportError as exc:
            raise RuntimeError(
                "openai is unavailable; install requirements-translate.txt"
            ) from exc
        self.model = model
        self.temperature = temperature
        self.operation_label = "整页翻译"
        self.request_type = "page_translation"
        self.page_number: int | str | None = None
        self.attempt = 1
        self.status_callback: Callable[[str], None] | None = None
        self._stats: dict[str, float | int] = {
            "total_requests": 0,
            "total_retries": 0,
            "prompt_tokens": 0,
            "completion_tokens": 0,
            "total_tokens": 0,
            "latency_seconds": 0.0,
            "failed_requests": 0,
            "review_failures": 0,
        }
        self._client = OpenAI(
            api_key=api_key,
            base_url=base_url.rstrip("/"),
            timeout=httpx.Timeout(
                timeout=read_timeout,
                connect=connect_timeout,
                read=read_timeout,
                write=connect_timeout,
                pool=connect_timeout,
            ),
            # Translation requests are intentionally single-attempt to avoid
            # silently spending tokens on repeated whole-page requests.
            max_retries=0,
        )
        # Qwen 3.7 Flash is a mixed-thinking model; translation and review do
        # not need chain-of-thought tokens.
        self._extra_body = {"enable_thinking": False}

    def _log_usage(self, response: Any, latency: float) -> None:
        usage = getattr(response, "usage", None)
        prompt_tokens = getattr(usage, "prompt_tokens", None)
        completion_tokens = getattr(usage, "completion_tokens", None)
        total_tokens = getattr(usage, "total_tokens", None)
        stats = getattr(self, "_stats", None)
        if stats is not None:
            stats["latency_seconds"] = float(stats["latency_seconds"]) + latency
            for key, value in (
                ("prompt_tokens", prompt_tokens),
                ("completion_tokens", completion_tokens),
                ("total_tokens", total_tokens),
            ):
                if isinstance(value, int):
                    stats[key] = int(stats[key]) + value
        payload = {
            "request_type": getattr(self, "request_type", "translation"),
            "page": getattr(self, "page_number", None),
            "model": self.model,
            "latency_seconds": round(latency, 3),
            "retry_count": max(0, int(getattr(self, "attempt", 1)) - 1),
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": total_tokens,
        }
        print("[TRANSLATION API]", json.dumps(payload), file=sys.stderr, flush=True)

    def set_operation(self, label: str, request_type: str | None = None) -> None:
        self.operation_label = label
        if request_type:
            self.request_type = request_type

    def set_request_context(self, request_type: str, page: int | str | None, attempt: int) -> None:
        self.request_type = request_type
        self.page_number = page
        self.attempt = attempt

    def record_failure(self, request_type: str) -> None:
        if not hasattr(self, "_stats"):
            return
        self._stats["failed_requests"] = int(self._stats["failed_requests"]) + 1
        if request_type == "page_review" or request_type.endswith("_review"):
            self._stats["review_failures"] = int(self._stats["review_failures"]) + 1

    def log_summary(self) -> None:
        stats = getattr(self, "_stats", None)
        if not stats:
            return
        requests = int(stats["total_requests"])
        payload = {
            "model": self.model,
            **stats,
            "average_latency_seconds": round(
                float(stats["latency_seconds"]) / requests, 3
            ) if requests else 0,
        }
        print("[TRANSLATION SUMMARY]", json.dumps(payload), file=sys.stderr, flush=True)

    def set_status_callback(self, callback: Callable[[str], None] | None) -> None:
        self.status_callback = callback

    def _report_status(self, message: str) -> None:
        callback = getattr(self, "status_callback", None)
        if callback is not None:
            callback(message)

    def _generate(
        self,
        system_prompt: str,
        user_prompt: str,
        max_completion_tokens: int,
        *,
        schema_name: str = "",
        schema: dict[str, Any] | None = None,
    ) -> str:
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]
        started = time.monotonic()
        self._stats["total_requests"] = int(self._stats["total_requests"]) + 1
        kwargs: dict[str, Any] = {
            "model": self.model,
            "messages": messages,
            "temperature": self.temperature,
            "max_completion_tokens": max_completion_tokens,
            "extra_body": self._extra_body,
        }
        if schema is not None:
            kwargs["response_format"] = {
                "type": "json_schema",
                "json_schema": {
                    "name": schema_name,
                    "strict": True,
                    "schema": schema,
                },
            }
        response = self._client.chat.completions.create(**kwargs)
        self._log_usage(response, time.monotonic() - started)
        if not response.choices:
            raise ValueError("translation API returned no choices")
        choice = response.choices[0]
        if getattr(choice, "finish_reason", None) in {"length", "max_tokens"}:
            raise CompletionTruncated("translation completion reached its token limit")
        content = choice.message.content
        if not isinstance(content, str) or not content.strip():
            raise ValueError("translation API returned empty content")
        return content

    def generate(self, system_prompt: str, user_prompt: str, max_tokens: int) -> str:
        return self._generate(system_prompt, user_prompt, max_tokens)

    def generate_structured(
        self,
        system_prompt: str,
        user_prompt: str,
        max_completion_tokens: int,
        *,
        schema_name: str,
        schema: dict[str, Any],
    ) -> str:
        return self._generate(
            system_prompt,
            user_prompt,
            max_completion_tokens,
            schema_name=schema_name,
            schema=schema,
        )


class LocalMLXBackend:
    """Resident MLX backend for Apple Silicon local translation."""

    def __init__(self, model_repo: str | None = None) -> None:
        try:
            from mlx_lm import generate, load
        except ImportError as exc:
            raise RuntimeError(
                "mlx-lm is unavailable; install requirements-translate.txt"
            ) from exc
        self.model = "local-qwen3-4b-instruct-2507"
        self.model_repo = (
            model_repo
            or os.getenv("TRANSLATION_LOCAL_MODEL_REPO", "").strip()
            or "mlx-community/Qwen3-4B-Instruct-2507-4bit"
        )
        self.operation_label = "本地整页翻译"
        self.request_type = "page_translation"
        self.page_number: int | str | None = None
        self.attempt = 1
        self.status_callback: Callable[[str], None] | None = None
        try:
            self.max_tokens = int(os.getenv("LOCAL_TRANSLATION_MAX_TOKENS", "16384"))
        except ValueError as exc:
            raise RuntimeError("LOCAL_TRANSLATION_MAX_TOKENS must be an integer") from exc
        if self.max_tokens < 512:
            raise RuntimeError("LOCAL_TRANSLATION_MAX_TOKENS must be at least 512")
        started = time.monotonic()
        self._model, self._tokenizer = load(self.model_repo)
        self._generate_fn = generate
        print(
            "[TRANSLATION LOCAL HEALTH] "
            f"model={self.model_repo} load_seconds={time.monotonic() - started:.3f}",
            file=sys.stderr,
            flush=True,
        )

    def set_operation(self, label: str, request_type: str | None = None) -> None:
        self.operation_label = label
        if request_type:
            self.request_type = request_type

    def set_request_context(self, request_type: str, page: int | str | None, attempt: int) -> None:
        self.request_type = request_type
        self.page_number = page
        self.attempt = attempt

    def set_status_callback(self, callback: Callable[[str], None] | None) -> None:
        self.status_callback = callback

    def _report_status(self, message: str) -> None:
        if self.status_callback is not None:
            self.status_callback(message)

    def record_failure(self, _request_type: str) -> None:
        return None

    def log_summary(self) -> None:
        return None

    def _prompt(self, system_prompt: str, user_prompt: str) -> str:
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]
        apply_template = getattr(self._tokenizer, "apply_chat_template", None)
        if callable(apply_template):
            try:
                return apply_template(
                    messages,
                    tokenize=False,
                    add_generation_prompt=True,
                    enable_thinking=False,
                )
            except TypeError:
                return apply_template(
                    messages,
                    tokenize=False,
                    add_generation_prompt=True,
                )
        return f"SYSTEM:\n{system_prompt}\n\nUSER:\n{user_prompt}\n\nASSISTANT:\n"

    def generate(self, system_prompt: str, user_prompt: str, max_tokens: int) -> str:
        prompt = self._prompt(system_prompt, user_prompt)
        token_limit = min(max_tokens, self.max_tokens)
        started = time.monotonic()
        result = self._generate_fn(
            self._model,
            self._tokenizer,
            prompt=prompt,
            max_tokens=token_limit,
        )
        if not isinstance(result, str) or not result.strip():
            raise ValueError("local translation model returned empty content")
        print(
            "[TRANSLATION LOCAL] "
            + json.dumps(
                {
                    "request_type": self.request_type,
                    "page": self.page_number,
                    "model": self.model_repo,
                    "latency_seconds": round(time.monotonic() - started, 3),
                    "max_tokens": token_limit,
                },
                ensure_ascii=False,
            ),
            file=sys.stderr,
            flush=True,
        )
        return result

    def generate_structured(
        self,
        system_prompt: str,
        user_prompt: str,
        max_completion_tokens: int,
        *,
        schema_name: str,
        schema: dict[str, Any],
    ) -> str:
        structured_system = (
            system_prompt
            + "\n\nReturn only valid JSON. The JSON must match this schema exactly:\n"
            + json.dumps(schema, ensure_ascii=False, separators=(",", ":"))
        )
        return self.generate(structured_system, user_prompt, max_completion_tokens)


class CompletionTruncated(RuntimeError):
    """The provider stopped at the requested output token cap."""


@dataclass
class ReviewResult:
    passed: bool
    score: float
    issues: list[str]
    corrected_translation: str
    reviewer_failed: bool = False


@dataclass
class TranslationResult:
    translation: str
    score: float | None
    issues: list[str]
    review: str


def normalize_source_text(value: Any) -> str:
    """Collapse OCR visual line wraps without creating new sentence boundaries."""
    return SPACE_RE.sub(" ", " ".join(str(value or "").splitlines())).strip()


def _remove_thinking(value: str) -> str:
    cleaned = THINK_RE.sub("", value).strip()
    if "</think>" in cleaned.lower():
        cleaned = re.split(r"</think>", cleaned, flags=re.IGNORECASE)[-1].strip()
    return cleaned


def clean_translation(value: Any) -> str:
    text = _remove_thinking(str(value or "").strip())
    text = CODE_FENCE_RE.sub("", text).strip()
    lines = []
    for line in text.splitlines():
        line = line.strip()
        line = re.sub(r"^>\s?", "", line)
        if line:
            lines.append(line)
    text = " ".join(lines)
    while True:
        stripped = PREFIX_RE.sub("", text, count=1).strip()
        if stripped == text:
            break
        text = stripped
    return SPACE_RE.sub(" ", text).strip().strip("`")


def _clean_json_payload(value: Any) -> str:
    text = _remove_thinking(str(value or "").strip())
    text = CODE_FENCE_RE.sub("", text).strip()
    try:
        payload = json.loads(text)
        if isinstance(payload, dict):
            return json.dumps(payload, ensure_ascii=False)
    except json.JSONDecodeError:
        pass

    # Accept one object surrounded by a small amount of prose. raw_decode
    # correctly handles braces and escaped quotes inside JSON strings; no
    # speculative repairs or string replacements are made.
    decoder = json.JSONDecoder()
    last_error: json.JSONDecodeError | None = None
    for match in re.finditer(r"\{", text):
        try:
            payload, end = decoder.raw_decode(text, match.start())
        except json.JSONDecodeError as exc:
            last_error = exc
            continue
        prefix = text[: match.start()].strip()
        suffix = text[end:].strip()
        if isinstance(payload, dict) and len(prefix) <= 256 and len(suffix) <= 256:
            return json.dumps(payload, ensure_ascii=False)
    if last_error is not None:
        raise last_error
    raise ValueError("structured response does not contain a JSON object")


def parse_review(value: Any, candidate: str) -> ReviewResult:
    payload = json.loads(_clean_json_payload(value))
    if not isinstance(payload, dict):
        raise ValueError("reviewer response must be a JSON object")
    passed = payload.get("passed")
    if not isinstance(passed, bool):
        raise ValueError("reviewer passed must be boolean")
    score = payload.get("score")
    if not isinstance(score, (int, float)) or isinstance(score, bool):
        raise ValueError("reviewer score must be numeric")
    score = float(score)
    if score > 1 and score <= 100:
        score /= 100
    if score < 0 or score > 1:
        raise ValueError("reviewer score must be between 0 and 1")
    raw_issues = payload.get("issues", [])
    if not isinstance(raw_issues, list):
        raise ValueError("reviewer issues must be an array")
    issues = [str(item).strip() for item in raw_issues if str(item).strip()]
    corrected = clean_translation(payload.get("corrected_translation", ""))
    if not corrected:
        corrected = candidate
    if passed and corrected != clean_translation(candidate):
        passed = False
        issues.append("reviewer corrected the candidate")
    return ReviewResult(passed, score, issues, corrected)


def explicit_context(segment: dict[str, Any]) -> str:
    for key in ("context", "paragraph", "block_text", "block"):
        value = segment.get(key)
        if isinstance(value, str) and normalize_source_text(value):
            return normalize_source_text(value)
        if isinstance(value, dict):
            for nested_key in ("text", "content"):
                nested = value.get(nested_key)
                if isinstance(nested, str) and normalize_source_text(nested):
                    return normalize_source_text(nested)
    return ""


def target_sentence(segment: dict[str, Any]) -> str:
    sentence = segment.get("sentence")
    if isinstance(sentence, str) and normalize_source_text(sentence):
        return normalize_source_text(sentence)
    return normalize_source_text(segment.get("text", ""))


def page_context(segments: list[dict[str, Any]], index: int, max_chars: int = 2400) -> str:
    direct = explicit_context(segments[index])
    if direct:
        target = target_sentence(segments[index])
        if target and target not in direct:
            available = max(0, max_chars - len(target) - 1)
            return f"{direct[:available]}\n{target}".strip()
        return direct[:max_chars]
    texts = [target_sentence(segment) for segment in segments]
    texts = [text for text in texts if text]
    if not texts:
        return target_sentence(segments[index])
    full = "\n".join(texts)
    if len(full) <= max_chars:
        return full
    # Keep a centered page window when a page contains unusually dense text.
    chosen: list[tuple[int, str]] = []
    used = 0
    for distance in range(len(segments)):
        candidates = [index] if distance == 0 else [index - distance, index + distance]
        for current in candidates:
            if current < 0 or current >= len(segments):
                continue
            text = target_sentence(segments[current])
            if not text or used + len(text) + 1 > max_chars:
                continue
            chosen.append((current, text))
            used += len(text) + 1
    chosen.sort(key=lambda item: item[0])
    return "\n".join(text for _, text in chosen)


