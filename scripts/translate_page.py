PREFIX_RE = re.compile(
    r"^(?:翻译(?:结果)?|中文(?:翻译)?|translation|chinese)\s*[:：]\s*",
    re.IGNORECASE,
)
CODE_FENCE_RE = re.compile(r"^```(?:json|text|markdown)?\s*|\s*```$", re.IGNORECASE)
THINK_RE = re.compile(r"<think>.*?</think>", re.IGNORECASE | re.DOTALL)
NUMBER_RE = re.compile(r"\d+(?:[.:/-]\d+)*")
SPACE_RE = re.compile(r"[ \t\u00a0]+")


def clean_phonetic(value: Any) -> str:
    """Normalize a model-returned IPA value without accepting explanations."""
    if not isinstance(value, str):
        return ""
    candidate = value.strip().strip("`\"'")
    if candidate.startswith("/") and candidate.endswith("/") and len(candidate) > 2:
        candidate = candidate[1:-1].strip()
    candidate = SPACE_RE.sub(" ", candidate)
    if not candidate or "*" in candidate or len(candidate) > 96:
        return ""
    # Chinese explanations, labels, and sentences are not IPA values.
    if any("\u3400" <= char <= "\u9fff" for char in candidate):
        return ""
    if candidate.casefold() in {"unknown", "n/a", "na", "none", "missing", "null"}:
        return ""
    return candidate


